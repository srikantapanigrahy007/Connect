import { createHash, createHmac } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { mkdir, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, resolve, sep } from 'node:path';
import { Readable } from 'node:stream';

/**
 * File storage for uploads (avatars, attachments). Binary data never goes into MongoDB; only the
 * server-generated key does. Callers depend only on this interface, so the driver can change
 * without touching message or profile logic.
 *
 * @typedef {object} FileStorage
 * @property {string} driver "local" or "s3".
 * @property {(key: string, data: Buffer, options?: { contentType?: string }) => Promise<void>} put
 * @property {(key: string) => Promise<boolean>} exists
 * @property {(key: string, range?: { start: number, end: number }) => Promise<import('node:stream').Readable>} read
 *   Streams the object (or the inclusive byte range).
 * @property {(key: string) => Promise<void>} remove Succeeds when the object is already gone.
 */

/** Keys are generated by the server: segments of [A-Za-z0-9_-.], separated by "/". */
const KEY_PATTERN = /^[A-Za-z0-9_-]+(?:\.[a-z0-9]+)?(?:\/[A-Za-z0-9_-]+(?:\.[a-z0-9]+)?)*$/;

function assertKey(key) {
  if (typeof key !== 'string' || key.length > 200 || !KEY_PATTERN.test(key)) {
    throw new Error('Invalid storage key');
  }
}

/**
 * Development driver: files in a local folder. Suitable for one server with a persistent disk
 * only. Many hosts have an ephemeral filesystem that is wiped on every deploy or restart, so use
 * the S3-compatible driver in production.
 *
 * @param {string} rootDir
 * @returns {FileStorage}
 */
export function createLocalStorage(rootDir) {
  const root = resolve(rootDir);

  /** Resolves a key inside the root, refusing anything that would escape it. */
  const pathOf = (key) => {
    assertKey(key);
    const path = resolve(root, key);
    if (!path.startsWith(root + sep)) throw new Error('Invalid storage key');
    return path;
  };

  return {
    driver: 'local',
    async put(key, data) {
      const path = pathOf(key);
      await mkdir(dirname(path), { recursive: true });
      // "wx" fails instead of overwriting an existing file.
      await writeFile(path, data, { flag: 'wx' });
    },
    async exists(key) {
      try {
        return (await stat(pathOf(key))).isFile();
      } catch {
        return false;
      }
    },
    async read(key, range) {
      const path = pathOf(key);
      const stream = createReadStream(path, range ? { start: range.start, end: range.end } : {});
      // Surface "not found" as a rejected promise instead of a stream error.
      await new Promise((resolveOpen, rejectOpen) => {
        stream.once('open', resolveOpen);
        stream.once('error', rejectOpen);
      });
      return stream;
    },
    async remove(key) {
      await rm(pathOf(key), { force: true });
    },
  };
}

// ── S3-compatible object storage (AWS S3, Cloudflare R2, MinIO, Backblaze B2, …) ─────────

const EMPTY_SHA256 = createHash('sha256').update('').digest('hex');
const sha256Hex = (data) => createHash('sha256').update(data).digest('hex');
const hmac = (key, data) => createHmac('sha256', key).update(data).digest();
const encodeRfc3986 = (value) =>
  encodeURIComponent(value).replace(
    /[!'()*]/g,
    (c) => `%${c.charCodeAt(0).toString(16).toUpperCase()}`,
  );

/**
 * AWS Signature Version 4 for one request. Returns the headers to send (including
 * Authorization). Exported for tests.
 *
 * @param {{ method: string, url: URL, headers?: Record<string, string>, payloadHash?: string, region: string, accessKeyId: string, secretAccessKey: string, now?: Date }} input
 */
export function signS3Request({
  method,
  url,
  headers = {},
  payloadHash = EMPTY_SHA256,
  region,
  accessKeyId,
  secretAccessKey,
  now = new Date(),
}) {
  const amzDate = now
    .toISOString()
    .replace(/[-:]/g, '')
    .replace(/\.\d{3}/, '');
  const date = amzDate.slice(0, 8);
  const all = {
    ...Object.fromEntries(Object.entries(headers).map(([k, v]) => [k.toLowerCase(), String(v)])),
    host: url.host,
    'x-amz-content-sha256': payloadHash,
    'x-amz-date': amzDate,
  };
  const names = Object.keys(all).sort();
  const canonicalHeaders = names.map((name) => `${name}:${all[name].trim()}\n`).join('');
  const signedHeaders = names.join(';');
  const canonicalQuery = [...url.searchParams]
    .map(([k, v]) => [encodeRfc3986(k), encodeRfc3986(v)])
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([k, v]) => `${k}=${v}`)
    .join('&');
  const canonicalRequest = [
    method,
    url.pathname,
    canonicalQuery,
    canonicalHeaders,
    signedHeaders,
    payloadHash,
  ].join('\n');
  const scope = `${date}/${region}/s3/aws4_request`;
  const stringToSign = ['AWS4-HMAC-SHA256', amzDate, scope, sha256Hex(canonicalRequest)].join('\n');
  const signingKey = hmac(
    hmac(hmac(hmac(`AWS4${secretAccessKey}`, date), region), 's3'),
    'aws4_request',
  );
  const signature = createHmac('sha256', signingKey).update(stringToSign).digest('hex');
  return {
    ...all,
    authorization: `AWS4-HMAC-SHA256 Credential=${accessKeyId}/${scope}, SignedHeaders=${signedHeaders}, Signature=${signature}`,
  };
}

/**
 * Private bucket driver over plain HTTPS (no SDK dependency). Objects are never public: every
 * read goes through the API, which checks access and streams the bytes. Credentials come from
 * environment variables and never reach the browser.
 *
 * @param {{ endpoint: string, region: string, bucket: string, accessKeyId: string, secretAccessKey: string, forcePathStyle: boolean, fetch?: typeof fetch }} options
 * @returns {FileStorage}
 */
export function createS3Storage(options) {
  const { endpoint, region, bucket, accessKeyId, secretAccessKey, forcePathStyle } = options;
  const doFetch = options.fetch ?? fetch;
  const base = new URL(endpoint);

  const urlOf = (key) => {
    assertKey(key);
    const url = new URL(base);
    if (forcePathStyle) {
      url.pathname = `/${bucket}/${key}`;
    } else {
      url.host = `${bucket}.${base.host}`;
      url.pathname = `/${key}`;
    }
    return url;
  };

  async function request(method, key, { body, headers = {} } = {}) {
    const url = urlOf(key);
    const payloadHash = body ? sha256Hex(body) : EMPTY_SHA256;
    const signed = signS3Request({
      method,
      url,
      headers,
      payloadHash,
      region,
      accessKeyId,
      secretAccessKey,
    });
    delete signed.host;
    return doFetch(url, { method, headers: signed, body });
  }

  const failure = async (operation, response) => {
    // The body may describe the bucket; keep it out of client-facing errors.
    await response.body?.cancel().catch(() => undefined);
    return new Error(`Object storage ${operation} failed with HTTP ${response.status}`);
  };

  return {
    driver: 's3',
    async put(key, data, { contentType = 'application/octet-stream' } = {}) {
      const response = await request('PUT', key, {
        body: data,
        headers: { 'content-type': contentType, 'content-length': String(data.length) },
      });
      if (!response.ok) throw await failure('upload', response);
      await response.body?.cancel().catch(() => undefined);
    },
    async exists(key) {
      const response = await request('HEAD', key);
      if (response.status === 404) return false;
      if (!response.ok) throw await failure('lookup', response);
      return true;
    },
    async read(key, range) {
      const response = await request('GET', key, {
        headers: range ? { range: `bytes=${range.start}-${range.end}` } : {},
      });
      if (!response.ok || !response.body) throw await failure('download', response);
      return Readable.fromWeb(response.body);
    },
    async remove(key) {
      const response = await request('DELETE', key);
      if (!response.ok && response.status !== 404) throw await failure('delete', response);
      await response.body?.cancel().catch(() => undefined);
    },
  };
}

/** Builds the configured driver (config.storage from app-config.js). */
export function createStorage(storageConfig) {
  if (storageConfig.driver === 's3') return createS3Storage(storageConfig.s3);
  return createLocalStorage(storageConfig.dir);
}
